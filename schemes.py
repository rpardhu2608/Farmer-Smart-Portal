import streamlit as st

def show():
    st.title("🔥 Government Schemes")

    st.subheader("1. PM-KISAN")
    st.write("Financial support of ₹6,000 per year to eligible farmers.")
    st.markdown("Official Website: https://pmkisan.gov.in")

    st.subheader("2. Pradhan Mantri Fasal Bima Yojana (PMFBY)")
    st.write("Crop insurance scheme for farmers.")
    st.markdown("Official Website: https://pmfby.gov.in")

    st.subheader("3. Fertilizer Subsidy")
    st.write("Government subsidy on fertilizers for farmers.")
    st.markdown("Official Website: https://fertiliser.gov.in")

    st.subheader("4. Soil Health Card Scheme")
    st.write("Provides soil testing reports and fertilizer recommendations.")
    st.markdown("Official Website: https://soilhealth.dac.gov.in")

    st.subheader("5. Kisan Credit Card (KCC)")
    st.write("Provides low-interest loans to farmers.")
    st.markdown("Official Website: https://www.myscheme.gov.in")